import type { KnowledgeNodeInput } from "./domain-research-cards";
import {
  node,
  type DomainIconKey,
  type ResearchBranch,
  type ResearchDomain,
} from "./domain-research-catalog";

type BranchSeed = {
  id: string;
  title: string;
  summary: string;
  nodes: Array<string | KnowledgeNodeInput>;
  iconKey?: DomainIconKey;
  active?: boolean;
};

function isKnowledgeNode(value: string | KnowledgeNodeInput): value is KnowledgeNodeInput {
  return typeof value !== "string";
}

function branch({ id, title, summary, nodes, iconKey = "book", active = false }: BranchSeed): ResearchBranch {
  const normalized = nodes.map((entry) => isKnowledgeNode(entry) ? entry : ({
    title: entry,
    description: `从基本概念、历史条件、代表案例和常见误解四个角度，建立对“${entry}”的可调用认识。`,
  }));
  return {
    id,
    title,
    cardSummary: summary,
    summary,
    guidingQuestion: `这一主干怎样改变我们理解${title}时的判断，并与其他分支发生联系？`,
    status: active ? "正在理解" : "尚未展开",
    iconKey,
    nodes: normalized,
    starterQuestions: [
      `${title}最核心的问题是什么？`,
      `哪些经典案例最能说明${title}？`,
      `我目前对${title}最大的认知缺口是什么？`,
    ],
  };
}

function topic(id: string, title: string, description: string): KnowledgeNodeInput {
  return { id, title, description };
}

function financeNode(
  title: string,
  description: string,
  concept: string,
  examples: [string, string, string],
  misconception: string,
) {
  const base = node(
    title,
    description,
    concept,
    `把“${title}”放进完整投资链路时，要同时看定义、计量方法、成立条件、传导关系和实际市场后果。概念只有能够解释价格、企业、组合或制度中的具体变化，才真正从术语变成可调用的认识。`,
    examples,
    misconception,
    `理解“${title}”时，你更需要先建立概念关系，还是先用一个真实市场案例检验？`,
    ["先建立概念关系", "先看市场案例"],
  );
  return {
    ...base,
    concept: [
      concept,
      `继续理解时，应至少说清“${title}”涉及哪些主体与变量、关系朝哪个方向变化、结论依赖什么条件，以及哪些证据会推翻当前解释。这样才能把一个熟悉的名词变成能够分析新问题的工具。`,
    ],
    context: [
      base.context?.[0] ?? "",
      "实际使用时可以写出一条传导链：环境或事件改变谁的激励与约束，继而怎样影响现金流、融资条件或供需，最后怎样进入估值、价格与组合风险；同时标出链条可能在哪一步中断。",
    ],
    confusion: [
      misconception,
      `如果只能复述“${title}”的定义，却不能给出一个成立案例、一个反例和一个需要继续查证的数据，仍然只是产生了术语熟悉感，还没有形成可靠认识。`,
    ],
  };
}

